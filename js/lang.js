function translatePageNodes(targetLang) {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
  let node;
  while ((node = walker.nextNode())) {
    if (!node.parentElement || node.parentElement.closest('.notranslate, script, style')) continue;
    if (!node._origText) node._origText = node.nodeValue;
    const trimmed = node._origText.trim();
    if (!trimmed) continue;

    if (targetLang === 'en') {
      node.nodeValue = node._origText;
    } else if (autoDictionary[targetLang] && autoDictionary[targetLang][trimmed]) {
      node.nodeValue = node._origText.replace(trimmed, autoDictionary[targetLang][trimmed]);
    }
  }
}

function changeLang(lang) {
  localStorage.setItem('locx_lang', lang);
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  translatePageNodes(lang);
}

document.addEventListener('DOMContentLoaded', () => {
  const topBar = document.querySelector('header.top-bar');
  if (topBar && !document.querySelector('.lang-switch')) {
    const switcher = document.createElement('div');
    switcher.className = 'lang-switch notranslate';
    ['en', 'de', 'da'].forEach(code => {
      const btn = document.createElement('button');
      btn.className = 'lang-btn';
      btn.dataset.lang = code;
      btn.textContent = code.toUpperCase();
      btn.onclick = () => changeLang(code);
      switcher.appendChild(btn);
    });
    topBar.appendChild(switcher);
  }
  const saved = localStorage.getItem('locx_lang') || 'en';
  setTimeout(() => changeLang(saved), 50);
});
